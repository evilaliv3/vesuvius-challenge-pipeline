#!/usr/bin/env python3
"""Write src/paper/references.tex: the entries body.tex cites, and nothing else, in citation order.

This is results/references.py restricted to this work, so that building this article never
rewrites the references of another work. It reads the shared library (paper/papers/library.tex,
frozen) and this work's src/paper/library-local.tex; a key in both, or a key in neither, stops it.

Usage: write_references.py
"""
import os, re, sys

S = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = "/data/repositories/vesuvius-challenge-pipeline-private/paper/papers/library.tex"
BODY = os.path.join(S, "paper", "body.tex")
LOCAL = os.path.join(S, "paper", "library-local.tex")
OUT = os.path.join(S, "paper", "references.tex")


def blocks(path):
    s = open(path).read()
    out = {}
    parts = re.split(r"(\\bibitem\{([a-zA-Z0-9_-]+)\})", s)
    for i in range(1, len(parts), 3):
        body = parts[i + 2] if i + 2 < len(parts) else ""
        out[parts[i + 1]] = parts[i] + re.split(r"\n%|\n\\bibitem", body)[0].rstrip()
    return out


def main():
    lib = blocks(LIB)
    local = blocks(LOCAL) if os.path.exists(LOCAL) else {}
    both = sorted(set(lib) & set(local))
    if both:
        sys.exit("write_references.py: library-local.tex repeats the shared library's %s" % both)
    lib.update(local)
    cited, seen = [], set()
    text = "\n".join(l for l in open(BODY).read().splitlines() if not l.lstrip().startswith("%"))
    for m in re.finditer(r"\\cite\{([^}]+)\}", text):
        for k in (x.strip() for x in m.group(1).split(",")):
            if k and k not in seen:
                seen.add(k)
                cited.append(k)
    missing = [k for k in cited if k not in lib]
    if missing:
        sys.exit("write_references.py: no entry for %s" % ", ".join(missing))
    with open(OUT, "w") as fh:
        fh.write("% Generated by src/tools/write_references.py. Do not edit.\n"
                 "% Only what this work's prose cites, in the order it first cites it.\n")
        for k in cited:
            fh.write("\n" + lib[k] + "\n")
    print("  references: %d entries in citation order: %s" % (len(cited), ", ".join(cited)))


if __name__ == "__main__":
    main()
