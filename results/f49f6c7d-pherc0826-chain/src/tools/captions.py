#!/usr/bin/env python3
"""Write src/paper/captions.tex: one caption macro per raster figure, its numbers taken from the
figure's own table.

Each raster tool writes evidence/figures/<fig>.csv with a `key` column and a caption file
<fig>-caption.txt in which every number is written {key}. This tool replaces each {key} with the
value of that key's row, formed as paper_numbers.py forms numbers (a plain number of four or more
digits before the point grouped), and a mention «Figure C1N» with a reference to that figure's
label. A {key} with no row, a key with two rows, a digit left in a caption outside the scroll's name
and a figure reference, or a figure without a label here, stops it: no caption carries a typed number.

Usage: captions.py
"""
import csv, os, re, sys

S = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIG = os.path.join(S, "evidence", "figures")
OUT = os.path.join(S, "paper", "captions.tex")
# figure stem -> (macro, label)
FIGS = {"c-f10-papyrus": ("CaptionPapyrus", "fig:papyrus"),
        "c-f12-a2-flags": ("CaptionAtwoFlags", "fig:atwo"),
        "c-f13-setseed": ("CaptionSetSeed", "fig:setseed"),
        "c-f16-certified-square": ("CaptionCertifiedSquare", "fig:certified"),
        "c-f17-where-squares": ("CaptionWhereSquares", "fig:where"),
        "c-f20-best-windows": ("CaptionBestWindows", "fig:windows"),
        "c-f21-r2c": ("CaptionRtwoC", "fig:r2c"),
        "c-f25-square-full": ("CaptionSquareFull", "fig:squarefull"),
        "c-f22-v8in-w016": ("CaptionVeinW", "fig:veinw"),
        "c-f23-v8in-0826": ("CaptionVeinSquare", "fig:veinsquare"),
        "c-f24-v8in-more": ("CaptionVeinMore", "fig:veinmore")}


def group(v):
    if not re.fullmatch(r"\d+(?:\.\d+)?", v):
        return v
    whole, _, frac = v.partition(".")
    return ("{:,}".format(int(whole)) if len(whole) >= 4 else whole) + ("." + frac if frac else "")


def main():
    out = ["% Generated by src/tools/captions.py from evidence/figures/<fig>.csv and <fig>-caption.txt. Do not edit."]
    for stem, (macro, label) in FIGS.items():
        rows = [r for r in csv.reader(open(os.path.join(FIG, stem + ".csv"))) if r and not r[0].startswith("#")]
        head, body = rows[0], rows[1:]
        ki, vi = head.index("key"), head.index("value")
        vals = {}
        for r in body:
            if not r[ki]:
                continue                       # a row the caption does not use
            if r[ki] in vals:
                sys.exit("captions.py: %s: key %s twice" % (stem, r[ki]))
            vals[r[ki]] = r[vi]
        cap = open(os.path.join(FIG, stem + "-caption.txt")).read().strip()
        miss = [k for k in re.findall(r"\{([a-z0-9_]+)\}", cap) if k not in vals]
        if miss:
            sys.exit("captions.py: %s: no row for %s" % (stem, miss))
        rest = re.sub(r"\{[a-z0-9_]+\}", "", cap).replace("PHerc. 0826", "")
        rest = re.sub(r"Figure C(1\d|2\d)", "", rest)
        if re.search(r"\d", rest):
            sys.exit("captions.py: %s: a typed digit in the caption: %s" % (stem, re.findall(r".{20}\d.{5}", rest)))
        def ref(m):
            s = "c-f%s-" % m.group(1)
            hit = [l for k, (_, l) in FIGS.items() if k.startswith(s)]
            if not hit:
                sys.exit("captions.py: %s names Figure C%s, which has no label" % (stem, m.group(1)))
            return "Figure~\\ref{%s}" % hit[0]
        t = cap.replace("PHerc. 0826", "PHerc.~0826")
        t = re.sub(r"Figure C(\d+)", ref, t)
        t = re.sub(r"\{([a-z0-9_]+)\}", lambda m: (vals[m.group(1)] if re.fullmatch(r"seed(_\d+)?", m.group(1)) else group(vals[m.group(1)])).replace("_", "\\_"), t)
        t = t.replace("%", "\\%")
        out.append("\\newcommand{\\%s}{%s Drawn by \\texttt{src/tools/%s.py}.}" % (macro, t, stem))
    open(OUT, "w").write("\n".join(out) + "\n")
    print("captions.py: %d captions to %s" % (len(FIGS), OUT))


if __name__ == "__main__":
    main()
