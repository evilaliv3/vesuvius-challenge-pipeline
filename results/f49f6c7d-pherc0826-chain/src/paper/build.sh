#!/usr/bin/env bash
# Build the article of results/f49f6c7d-pherc0826-chain, copied on 2026-09-28 from the build of
# results/f211b3cf-villa-tracer-corrections with its gates kept, and put it at <public folder>/article.pdf.
#
# Gates, before and after latexmk:
#   P. PENDING: paper_numbers.py exits 3 while a file it needs does not exist yet. The article is
#      then REFUSED. A pending macro is never defined, so it cannot print; and every macro that
#      waits for a file must sit inside a «%% PENDING-BEGIN» ... «%% PENDING-END» block of body.tex,
#      or even the preview is refused.
#   1. no long dash in the sources; house_gates.py (dashes, AI tells, title, bio) on the sources;
#   2. every \cite has a \bibitem (references.tex is written by src/tools/write_references.py);
#   3. every \includegraphics exists and is named by a script of src/tools;
#   4. the side stripe; 5. latexmk -halt-on-error; 6. zero «LaTeX Warning» lines;
#   7. no overfull box wider than 2 pt (stricter than the house's 5 pt);
#   8. /CreationDate and /ModDate are SOURCE_DATE_EPOCH (check_build_date.py);
#   9. pdf_pages.py counts the pages three ways;
#  12. the figures included are the figures on disk, by name;
#  13. no escaped backslash in the typeset text;
#  15. paper_numbers.py and both figure tools run from src/tools, and each figure tool rewrites its
#      shipped plotted table row for row; the figure preamble equals results/figpreamble.tex;
#  english_only.py on the folder, bib_order.py on the article;
#   Q. every ``quotation'' of body.tex is found verbatim in its saved source (check_quotes.py).
#
# PREVIEW=1 is the only way to typeset while a measurement is pending. It copies src/paper to a
# scratch folder, drops from body.tex every PENDING block that uses a macro not yet written, builds
# there with every other gate, and writes the PDF to $PREVIEW_DIR (default
# /data/scrollagent/outputs/artifacts/fifth-work). It NEVER writes article.pdf.
#
# Usage: ./build.sh            the article, refused while anything is pending
#        PREVIEW=1 ./build.sh  a preview, never the article
export SOURCE_DATE_EPOCH=${SOURCE_DATE_EPOCH:-1790726400}   # 2026-09-30T00:00:00Z, the build day of v5
export FORCE_SOURCE_DATE=1
PUBLIC=${PAPER_PUBLIC:-/data/repositories/vesuvius-challenge-pipeline-private/results/f49f6c7d-pherc0826-chain}
BUILD=${PAPER_BUILD_DIR:-$PUBLIC/src/paper/build}
PREVIEW=${PREVIEW:-0}
PREVIEW_DIR=${PREVIEW_DIR:-/data/scrollagent/outputs/artifacts/fifth-work}
PY=${SA_PY:-/data/scrollagent/.venv/bin/python}; [ -x "$PY" ] || PY=python3

set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
PRIV=$(dirname "$HERE")
NAME=pherc0826-chain
rc=0

python3 - "$HERE/published-date.tex" "$SOURCE_DATE_EPOCH" <<'PYGATE' || exit 1
import datetime, re, sys
p, epoch = sys.argv[1], int(sys.argv[2])
src = "\n".join(re.sub(r"(?<!\\)%.*$", "", ln) for ln in open(p).read().splitlines())
found = re.findall(r"\\newcommand\{\\PublishedDateIso\}\{([^}]*)\}", src)
if not found:
    sys.exit("build: %s defines no \\PublishedDateIso" % p)
iso = found[-1].strip()
if iso and datetime.date.fromisoformat(iso) > datetime.datetime.fromtimestamp(epoch, datetime.timezone.utc).date():
    sys.exit("build: the publication date is after the build date, refused")
print("  published date: %s" % (iso or "none, the stripe says not yet published"))
PYGATE

{ printf '%% Generated by paper/build.sh from SOURCE_DATE_EPOCH. Do not edit by hand.\n'
  printf '\\newcommand{\\BuildDate}{%s\\xspace}\n' "$(date -u -d "@$SOURCE_DATE_EPOCH" +%Y-%m-%d)"
  printf '\\newcommand{\\BuildDateLong}{%s}\n' "$(date -u -d "@$SOURCE_DATE_EPOCH" "+%-d %B %Y")"
} > "$HERE/build-date.tex"
echo "  build date $(date -u -d "@$SOURCE_DATE_EPOCH" +%Y-%m-%d) (SOURCE_DATE_EPOCH=$SOURCE_DATE_EPOCH), preview=$PREVIEW"

# GATE P and 15, together: the numbers, run from src/tools as a reader runs them.
# The derived tables and the cut off decisions, from the snapshot, before the numbers.
( cd "$PRIV" && python3 tools/chain_summary.py > /dev/null && python3 tools/area_summary.py > /dev/null && python3 tools/fibre_summary.py > /dev/null && python3 tools/checks_summary.py > /dev/null && python3 tools/v8in_summary.py > /dev/null && python3 tools/v8in_reads.py > /dev/null && python3 tools/corrections_list.py > /dev/null && python3 tools/cuts_summary.py > /dev/null && python3 tools/pin_check.py tools/c-f25-square-full-pins.csv > /dev/null \
    && python3 tools/arms_paired.py > /dev/null && python3 tools/square95.py > /dev/null && python3 tools/caps.py > /dev/null && python3 tools/cutoff.py ) || { echo "build: refused, a derived table"; exit 1; }
( cd "$PRIV" && "$PY" tools/paper_numbers.py ); prc=$?
if [ "$prc" != "0" ] && [ "$prc" != "3" ]; then echo "build: refused, paper_numbers.py failed ($prc)"; exit 1; fi
if [ "$prc" = "3" ] && [ "$PREVIEW" != "1" ]; then
  echo "build: REFUSED, numbers are pending (src/paper/pending.txt); the article is not built"
  cut -f2 "$HERE/pending.txt" | sort | uniq -c | sed 's/^/   /'
  exit 1
fi
python3 - "$HERE/body.tex" "$HERE/pending.txt" <<'PYPEND' || { echo "build: refused by gate P"; exit 1; }
import re, sys
body = open(sys.argv[1]).read().splitlines()
pend = {l.split("\t")[0] for l in open(sys.argv[2]) if l.strip()}
inside, bad = False, []
for i, l in enumerate(body, 1):
    if l.startswith("%% PENDING-BEGIN"):
        if inside: sys.exit("   body.tex line %d: a PENDING block opened inside another" % i)
        inside = True; continue
    if l.startswith("%% PENDING-END"):
        if not inside: sys.exit("   body.tex line %d: a PENDING-END with no BEGIN" % i)
        inside = False; continue
    if l.lstrip().startswith("%"): continue
    for m in re.findall(r"\\([A-Za-z]+)", l):
        if m in pend and not inside:
            bad.append((i, m))
if inside: sys.exit("   body.tex: a PENDING block is never closed")
for i, m in bad: print("   body.tex line %d: \\%s is pending and is outside a PENDING block" % (i, m))
if bad: sys.exit(1)
print("  pending: %d macro(s) pending, every use inside a PENDING block" % len(pend))
PYPEND

FIGTMP=$(mktemp "${TMPDIR:-/data/tmp}/c-fig-XXXXXX.csv") || exit 1
for f in c-f1-pipeline c-f2-best-square c-f3-stevens-formula c-f18-arms-steps c-f19-yield-waves; do
  ( cd "$PRIV" && "$PY" tools/$f.py --out "$FIGTMP" 2>/dev/null \
      && cmp -s <(tail -n +2 "$FIGTMP") <(tail -n +2 evidence/figures/$f.csv) ) \
    || { rm -f "$FIGTMP"; echo "build: refused by gate 15, $f.py does not rewrite its shipped plotted table"; exit 1; }
done
rm -f "$FIGTMP"
if [ -f "$PUBLIC/../figpreamble.tex" ] && ! cmp -s "$PUBLIC/../figpreamble.tex" "$PRIV/tools/figpreamble.tex"; then
  echo "build: refused by gate 15, src/tools/figpreamble.tex has drifted from results/figpreamble.tex"; exit 1
fi
( cd "$PRIV" && "$PY" -c "import sys; sys.path.insert(0, 'tools'); import numpy, csv" ) || { echo "build: src/tools shadows numpy"; exit 1; }
echo "  gate 15: paper_numbers.py and both figure tools run from src/tools and rewrite their tables; figpreamble same"

# GATE 15 for the rasters: each raster tool rerun with --out must rewrite its shipped table row for
# row (render_rasters.sh --check); the load guard is lifted for this check only, since it compares
# rows, not times. Then the captions, whose numbers come from those tables.
( cd "$PRIV/tools" && SA_FIGURES_IGNORE_LOAD=1 nice -n 10 bash render_rasters.sh --check > "${TMPDIR:-/data/tmp}/c-raster-check.log" 2>&1 ) \
  || { tail -5 "${TMPDIR:-/data/tmp}/c-raster-check.log"; echo "build: refused by gate 15, a raster tool no longer writes its shipped table"; exit 1; }
echo "  gate 15: every raster tool rewrites its shipped table (render_rasters.sh --check)"
python3 "$PRIV/tools/captions.py" || { echo "build: refused, a caption"; exit 1; }
python3 "$PRIV/tools/write_references.py" || exit 1
python3 "$PRIV/tools/check_quotes.py" || { echo "build: refused, a quotation is not in its source"; exit 1; }
# GATE F (director 2026-09-28T12:21:38Z): every stated value agrees with the shared facts table of
# results/facts, whose check is written by another agent. Absent, the preview says so and goes on;
# the article refuses, because an article whose facts were never compared is not final.
FACTS=$PUBLIC/../facts/check_facts.py
if [ -f "$FACTS" ]; then
  python3 "$FACTS" "$PUBLIC" || { echo "build: refused by gate F, a stated value disagrees with results/facts"; exit 1; }
elif [ "$PREVIEW" = "1" ]; then
  echo "  gate F: results/facts/check_facts.py does not exist yet; the preview goes on, the article would refuse"
else
  echo "build: refused by gate F, results/facts/check_facts.py does not exist yet"; exit 1
fi

# The folder the article is typeset in: src/paper itself, or a scratch copy for the preview.
WORK=$HERE
if [ "$PREVIEW" = "1" ]; then
  SCR=$(mktemp -d "${TMPDIR:-/data/tmp}/c-preview-XXXXXX") || exit 1
  cp -r "$HERE" "$SCR/paper" && rm -rf "$SCR/paper/build"
  WORK=$SCR/paper
  python3 - "$WORK/body.tex" "$HERE/pending.txt" <<'PYSTRIP' || exit 1
import re, sys
p = sys.argv[1]
pend = {l.split("\t")[0] for l in open(sys.argv[2]) if l.strip()}
out, block, dropped = [], None, 0
for l in open(p).read().splitlines():
    if l.startswith("%% PENDING-BEGIN"):
        block = [l]; continue
    if block is not None:
        block.append(l)
        if l.startswith("%% PENDING-END"):
            used = {m for x in block for m in re.findall(r"\\([A-Za-z]+)", x)}
            if used & pend:
                dropped += 1
                out.append("%% preview: a PENDING block dropped here")
            else:
                out.extend(block)
            block = None
        continue
    out.append(l)
open(p, "w").write("\n".join(out) + "\n")
print("  preview: %d PENDING block(s) dropped" % dropped)
PYSTRIP
  # A figure another agent has drawn and the text does not include yet is set aside in the
  # PREVIEW copy only, and named; the article build keeps gate 12 strict on the real folder.
  python3 - "$WORK/body.tex" "$WORK/figures" <<'PYSET'
import os, re, sys
used = set(re.findall(r"\\includegraphics\[[^]]*\]\{figures/([^}]+)\}", open(sys.argv[1]).read()))
for f in sorted(os.listdir(sys.argv[2])):
    stem = f.rsplit(".", 1)[0]
    if f.endswith((".pdf", ".png")) and re.match(r"^[a-z]-f\d+-", f) and stem not in used:
        os.remove(os.path.join(sys.argv[2], f))
        print("  preview: %s is on disk and not included yet, left out of the preview" % f)
PYSET
  BUILD=$SCR/build
fi
created=""; [ -d "$BUILD" ] || created=$BUILD
mkdir -p "$BUILD" || exit 1
TEX=$WORK/$NAME.tex

for f in "$TEX" "$WORK/body.tex" "$WORK/author-works.tex"; do
  if grep -qE -- '---|\xe2\x80\x94|\xe2\x80\x93' "$f"; then echo "  !! long dash in $(basename "$f")"; rc=1; fi
done
python3 /data/scrollagent/tools/house_gates.py "$TEX" "$WORK/body.tex" "$PUBLIC/README.md" || rc=1
if ! grep -q '\\input{sidestripe}' "$TEX" || ! grep -qE '\\sidestripe\{[A-Za-z0-9][A-Za-z0-9-]*\}' "$TEX"; then
  echo "  !! no side stripe"; rc=1
fi

python3 - "$TEX" "$PRIV/tools" <<'PY' || rc=1
import re, sys, pathlib
tex = pathlib.Path(sys.argv[1]); tools = pathlib.Path(sys.argv[2])
def expand(s, d=0):
    def sub(m):
        p = tex.parent / (m.group(1) + ("" if m.group(1).endswith(".tex") else ".tex"))
        return expand(p.read_text(), d + 1) if p.exists() and d < 3 else ""
    return re.sub(r"\\input\{([^}]+)\}", sub, s)
full = expand(tex.read_text())
full = "\n".join(l for l in full.splitlines() if not l.lstrip().startswith("%"))
cited = {k.strip() for m in re.finditer(r"\\cite\{([^}]+)\}", full) for k in m.group(1).split(",")}
have = set(re.findall(r"\\bibitem\{([^}]+)\}", full))
scripts = "\n".join(p.read_text(errors="ignore") for p in sorted(tools.glob("*.py")) + sorted(tools.glob("*.sh")) + sorted(tools.glob("*.tex")))
figs = [m.group(1) for m in re.finditer(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", full)]
nofig = [f for f in figs if pathlib.Path(f).stem not in scripts]
missing = [f for f in figs if not any((tex.parent / (f + e)).exists() for e in ("", ".pdf", ".png"))]
bad = sorted(cited - have)
if bad: print("  !! cited without a bibitem:", bad)
if sorted(have - cited): print("  !! bibitems never cited:", sorted(have - cited))
if nofig: print("  !! figures with no producing script:", nofig)
if missing: print("  !! figure files missing:", missing)
ok = not (bad or nofig or missing or (have - cited))
print("  citations and figures:", "ok" if ok else "PROBLEMS")
sys.exit(0 if ok else 1)
PY

python3 - "$WORK/body.tex" "$WORK/figures" <<'PYFIG' || rc=1
import os, re, sys
used = set(re.findall(r"\\includegraphics\[[^]]*\]\{figures/([^}]+)\}",
                      "\n".join(l for l in open(sys.argv[1]) if not l.lstrip().startswith("%"))))
have = {f.rsplit(".", 1)[0] for f in (os.listdir(sys.argv[2]) if os.path.isdir(sys.argv[2]) else [])
        if f.endswith((".pdf", ".png")) and re.match(r"^[a-z]-f\d+-", f)}
if used != have:
    print("build: figures included %s, on disk %s" % (sorted(used), sorted(have))); sys.exit(1)
print("  figures: %d included, %d on disk, the same names" % (len(used), len(have)))
PYFIG
python3 - "$WORK/body.tex" <<'PYBS' || rc=1
import re, sys
b = open(sys.argv[1]).read()
hits = [m.start() for m in re.finditer(r"\\textbackslash\{\}", b)] + [m.start() for m in re.finditer(r"\\\\(?=[A-Za-z])", b)]
if hits: print("build: %d escaped backslash(es) in body.tex" % len(hits)); sys.exit(1)
print("  no escaped backslash in the typeset text")
PYBS
python3 "$PRIV/tools/english_only.py" "$PUBLIC" --quiet || rc=1
python3 "$PRIV/tools/bib_order.py" "$TEX" || rc=1

cd "$WORK" || exit 1
if nice -n 10 env TEXINPUTS=".:$WORK//:$WORK/cls:" latexmk -pdf -interaction=nonstopmode -halt-on-error \
     -outdir="$BUILD" "$NAME.tex" > "$BUILD/build.log" 2>&1; then
  warns=$(grep -c "LaTeX Warning" "$BUILD/$NAME.log" || true)
  over=$(awk 'match($0,/^Overfull \\hbox \(([0-9.]+)pt too wide\)/,m) && m[1]+0 > 2 {print "    " $0}' "$BUILD/$NAME.log")
  pages=$(tr -d '\n' < "$BUILD/$NAME.log" | grep -o "Output written on[^(]*([0-9]* pages" | grep -o "[0-9]* pages" | head -1)
  echo "  -> $pages, LaTeX warnings: $warns"
  if [ "$warns" != "0" ]; then grep "LaTeX Warning" "$BUILD/$NAME.log" | head -20; rc=1; fi
  if [ -n "$over" ]; then echo "  !! overfull boxes wider than 2 pt:"; echo "$over"; rc=1; fi
  python3 "$PRIV/tools/check_build_date.py" "$BUILD/$NAME.pdf" "$SOURCE_DATE_EPOCH" || rc=1
  if [ "$rc" = "0" ]; then
    if [ "$PREVIEW" = "1" ]; then
      mkdir -p "$PREVIEW_DIR"
      cp "$BUILD/$NAME.pdf" "$PREVIEW_DIR/$NAME-preview.pdf"
      echo "  -> $PREVIEW_DIR/$NAME-preview.pdf (a PREVIEW: article.pdf left as it was)"
      python3 "$PRIV/tools/pdf_pages.py" "$PREVIEW_DIR/$NAME-preview.pdf" || rc=1
    else
      cp "$BUILD/$NAME.pdf" "$PUBLIC/article.pdf"
      echo "  -> $PUBLIC/article.pdf"
      python3 "$PRIV/tools/pdf_pages.py" "$PUBLIC/article.pdf" || rc=1
    fi
  else
    echo "  !! a gate failed, nothing written"
  fi
else
  echo "  !! latexmk failed, see $BUILD/build.log"; grep -A3 "^!" "$BUILD/$NAME.log" | head -20; rc=1
fi
if [ -n "$created" ]; then rm -rf "$created"; rmdir "$(dirname "$created")" 2>/dev/null; fi
[ "$PREVIEW" = "1" ] && rm -rf "$SCR"
echo "build done (rc=$rc)"
exit $rc
